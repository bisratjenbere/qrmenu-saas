// ─── Transliteration Map (Bidirectional) ──────────────────────────
// Maps Amharic dish names to English and vice versa for auto-suggestions.
export const TRANSLITERATION_MAP: Record<string, string> = {};
ETHIOPIAN_DISHES.forEach(dish => {
  TRANSLITERATION_MAP[dish.nameAmharic] = dish.name;
  TRANSLITERATION_MAP[dish.name.toLowerCase()] = dish.nameAmharic;
});

// ─── Lookup Helpers ───────────────────────────────────────────────
export function findDishByAmharic(query: string): EthiopianDish[] {
  const q = query.trim();
  return ETHIOPIAN_DISHES.filter(d =>
    d.nameAmharic.includes(q) || d.categoryAmharic.includes(q)
  );
}

export function findDishByEnglish(query: string): EthiopianDish[] {
  const q = query.trim().toLowerCase();
  return ETHIOPIAN_DISHES.filter(d =>
    d.name.toLowerCase().includes(q) || d.category.toLowerCase().includes(q)
  );
}

export function searchDishes(query: string): EthiopianDish[] {
  const q = query.trim();
  if (!q) return ETHIOPIAN_DISHES;
  // Check if query contains Amharic characters (Unicode range for Ethiopic)
  const isAmharic = /[\u1200-\u137F]/.test(q);
  if (isAmharic) return findDishByAmharic(q);
  return findDishByEnglish(q);
}

export function getTransliteration(input: string): string | null {
  return TRANSLITERATION_MAP[input] || TRANSLITERATION_MAP[input.toLowerCase()] || null;
}

